import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

import { GENESIS_WATER_CELLS_V1 } from '../spacetimedb/src/waterWorld';
import { GENESIS_WATER_REVISION_ENABLED_CELLS_V1 } from '../spacetimedb/src/waterRevision';

type AxialRow = Readonly<{ q: number; r: number }>;
type OceanRow = AxialRow & Readonly<{ regime: string; depthCells: number }>;
type CoordinateRun = readonly [q: number, firstR: number, lastR: number];
type OceanDepthRun = readonly [q: number, firstR: number, lastR: number, depth: number];

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const outputPath = resolve(repositoryRoot, 'spacetimedb/src/greaterRealmFrozenWaterCatalog.ts');

function assertAxialRow(row: AxialRow): void {
  if (
    !Number.isSafeInteger(row.q)
    || !Number.isSafeInteger(row.r)
    || !Number.isSafeInteger(-row.q - row.r)
  ) throw new Error('FROZEN_WATER_CATALOG_COORDINATE_INVALID');
}

function buildCoordinateRuns(rows: readonly AxialRow[]): CoordinateRun[] {
  const sorted = [...rows].sort((left, right) => left.q - right.q || left.r - right.r);
  const runs: CoordinateRun[] = [];
  for (const row of sorted) {
    assertAxialRow(row);
    const previous = runs[runs.length - 1];
    if (previous !== undefined && previous[0] === row.q && row.r <= previous[2]) {
      throw new Error('FROZEN_WATER_CATALOG_COORDINATE_DUPLICATE');
    }
    if (previous !== undefined && previous[0] === row.q && row.r === previous[2] + 1) {
      runs[runs.length - 1] = [previous[0], previous[1], row.r];
    } else {
      runs.push([row.q, row.r, row.r]);
    }
  }
  return runs;
}

function buildOceanDepthRuns(rows: readonly OceanRow[]): OceanDepthRun[] {
  const sorted = [...rows].sort((left, right) => left.q - right.q || left.r - right.r);
  const runs: OceanDepthRun[] = [];
  for (const row of sorted) {
    assertAxialRow(row);
    if (row.regime !== 'ocean' || !Number.isSafeInteger(row.depthCells) || row.depthCells < 1) {
      throw new Error('FROZEN_WATER_CATALOG_OCEAN_ROW_INVALID');
    }
    const previous = runs[runs.length - 1];
    if (previous !== undefined && previous[0] === row.q && row.r <= previous[2]) {
      throw new Error('FROZEN_WATER_CATALOG_OCEAN_COORDINATE_DUPLICATE');
    }
    if (
      previous !== undefined
      && previous[0] === row.q
      && row.r === previous[2] + 1
      && row.depthCells === previous[3]
    ) {
      runs[runs.length - 1] = [previous[0], previous[1], row.r, previous[3]];
    } else {
      runs.push([row.q, row.r, row.r, row.depthCells]);
    }
  }
  return runs;
}

function formatRuns<T extends readonly number[]>(runs: readonly T[]): string {
  return runs.map(run => `  [${run.join(', ')}],`).join('\n');
}

function renderModule(
  oceanRuns: readonly OceanDepthRun[],
  activeRuns: readonly CoordinateRun[],
): string {
  return `/**
 * Generated by scripts/generate-greater-realm-frozen-water-catalog.ts.
 * Standalone frozen axial water authority for the isolated PTR module.
 * Do not add imports here: this file is also compiled as a provider bundle.
 */
type AxialRange = readonly [q: number, firstR: number, lastR: number, ...metadata: number[]];
type OceanDepthRange = readonly [q: number, firstR: number, lastR: number, depth: number];

const OCEAN_DEPTH_RANGES: readonly OceanDepthRange[] = Object.freeze([
${formatRuns(oceanRuns)}
]);

const ACTIVE_WATER_RANGES: readonly AxialRange[] = Object.freeze([
${formatRuns(activeRuns)}
]);

function isValidAxialCoordinate(q: number, r: number): boolean {
  return Number.isSafeInteger(q)
    && Number.isSafeInteger(r)
    && Number.isSafeInteger(-q - r);
}

function findRange<T extends AxialRange>(
  ranges: readonly T[],
  q: number,
  r: number,
): T | undefined {
  let low = 0;
  let high = ranges.length;
  while (low < high) {
    const middle = low + Math.floor((high - low) / 2);
    const range = ranges[middle]!;
    if (q < range[0] || (q === range[0] && r < range[1])) {
      high = middle;
    } else if (q > range[0] || (q === range[0] && r > range[2])) {
      low = middle + 1;
    } else {
      return range;
    }
  }
  return undefined;
}

/** Returns the frozen ocean depth at a canonical local axial coordinate. */
export function canonicalOceanDepthAt(q: number, r: number): number | undefined {
  if (!isValidAxialCoordinate(q, r)) return undefined;
  return findRange(OCEAN_DEPTH_RANGES, q, r)?.[3];
}

/** True for any coordinate in the canonical active ocean or river set. */
export function isCanonicalWaterCoordinate(q: number, r: number): boolean {
  if (!isValidAxialCoordinate(q, r)) return false;
  return findRange(ACTIVE_WATER_RANGES, q, r) !== undefined;
}
`;
}

function main(): void {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('FROZEN_WATER_CATALOG_ARGUMENT_INVALID');
  }

  const allByCoordinate = new Map<string, (typeof GENESIS_WATER_CELLS_V1)[number]>();
  for (const row of GENESIS_WATER_CELLS_V1) {
    assertAxialRow(row);
    const key = `${row.q},${row.r}`;
    if (allByCoordinate.has(key)) throw new Error('FROZEN_WATER_CATALOG_SOURCE_DUPLICATE');
    allByCoordinate.set(key, row);
  }

  const activeRows = [...GENESIS_WATER_REVISION_ENABLED_CELLS_V1];
  for (const row of activeRows) {
    const source = allByCoordinate.get(`${row.q},${row.r}`);
    if (
      source === undefined
      || source.cellKey !== row.cellKey
      || source.regime !== row.regime
      || (row.regime !== 'ocean' && row.regime !== 'river')
    ) throw new Error('FROZEN_WATER_CATALOG_ACTIVE_SOURCE_INVALID');
  }

  const oceanRows = activeRows.filter((row): row is typeof row & OceanRow => row.regime === 'ocean');
  const activeRuns = buildCoordinateRuns(activeRows);
  const oceanRuns = buildOceanDepthRuns(oceanRows);
  const generated = renderModule(oceanRuns, activeRuns);

  if (args[0] === '--check') {
    const current = readFileSync(outputPath, 'utf8');
    if (current !== generated) throw new Error('FROZEN_WATER_CATALOG_STALE');
    return;
  }
  writeFileSync(outputPath, generated, { encoding: 'utf8' });
}

main();
